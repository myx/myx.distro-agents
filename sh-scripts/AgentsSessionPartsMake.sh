#!/usr/bin/env bash

##
## AgentsSessionPartsMake.sh -- prints, writes or checks sh-lib/session/AgentsSessionParts.include: the sessions store's leaf and its
## two builders, for a caller that must not load the session concern's store include -- a client hook on the tool-call path. The
## blocks are the store include's own text, under this file's names, so the store keeps one spelling of each rule.
##
##   [<package root>] [--print|--write|--check]
##     --print   the file's text on stdout, which is the default
##     --write   puts that text in <package root>/sh-lib/session/AgentsSessionParts.include
##     --check   compares it with that file, rc 1 and a diff on stderr where they differ, rc 0 where they agree
##
## NOTE:
## Designed to be able to run without distro context.
##

set -u

makeMode="print" makeRoot=""
while [ $# -gt 0 ] ; do
	case "$1" in
		--print|--write|--check) makeMode="${1#--}" ; shift ;;
		-*) echo "⛔ ERROR: AgentsSessionPartsMake: invalid option: $1" >&2 ; exit 1 ;;
		*) makeRoot="$1" ; shift ;;
	esac
done
makeRoot="${makeRoot:-$( cd "$( dirname "$0" )/.." && pwd -P )}" || exit 1
makeStore="$makeRoot/sh-lib/session/AgentsTools.SessionStore.include"
makeParts="$makeRoot/sh-lib/session/AgentsSessionParts.include"
[ -f "$makeStore" ] || { echo "⛔ ERROR: AgentsSessionPartsMake: no store include at $makeStore" >&2 ; exit 1; }

## The four blocks, by their names in the store include: the leaf, and the three builders, each one the next needs.
makeBlocks="agentsSessionStoreLeaf AgentsSessionStoreDirInto AgentsSessionFolderInto AgentsSessionPartInto"
IFS= read -r -d '' makeHeader <<'HEADER' || :
#!/usr/bin/env bash
# ^^^ for syntax checking in the editor only

##
## AgentsSessionParts.include -- the sessions store's leaf and its builders, for a caller that must not load the store include: a
## client hook on the tool-call path. GENERATED by sh-scripts/AgentsSessionPartsMake.sh, whose text these blocks are; the store
## include holds their one source. Never edit this file: a fix belongs there, and a run of the generator after it.
##
HEADER

## Each block whole, from the store include, in its own order; then the store's names, swapped for this file's, so no name is
## defined in two files and a reader can tell which of the two builders it holds.
makeText="$( makeHeader="$makeHeader" LC_ALL=C awk -v want="$makeBlocks" '
	BEGIN { count = split(want, block, " ") ; for (at = 1 ; at <= count ; at++) wanted[block[at]] = 1 ; printed = 0 }
	/^[A-Za-z_][A-Za-z0-9_]*(\(\)|=)/ {
		name = $0 ; sub(/[\(\)=].*/, "", name)
		if (name in wanted) {
			if (printed) print ""
			printed = 1
			if (index($0, "()") > 0) inside = 1
			print
			next
		}
	}
	!inside { next }
	{ print }
	$0 == "}" { inside = 0 }
	END { printf "" }
' "$makeStore" )"
[ -n "$makeText" ] || { echo "⛔ ERROR: AgentsSessionPartsMake: $makeStore gave none of: $makeBlocks" >&2 ; exit 1; }
makeText="$( printf '%s\n%s\n' "$makeHeader" "$makeText" | LC_ALL=C sed -e 's/agentsSessionStoreLeaf/agentsSessionPartsLeaf/g' \
	-e 's/AgentsSessionStoreDirInto/AgentsSessionPartsStoreDirInto/g' \
	-e 's/AgentsSessionFolderInto/AgentsSessionPartsFolderInto/g' \
	-e 's/AgentsSessionPartInto/AgentsSessionPartsPartInto/g' )"

case "$makeMode" in
	write)
		## Beside the target and renamed over, so a reader never sees half a file.
		makeTemp="$( mktemp "$makeParts.XXXXXX" )" || exit 1
		if printf '%s\n' "$makeText" > "$makeTemp" && chmod 644 "$makeTemp" && mv -f "$makeTemp" "$makeParts" ; then
			exit 0
		fi
		rm -f "$makeTemp"
		echo "⛔ ERROR: AgentsSessionPartsMake: could not write $makeParts" >&2
		exit 1
	;;
	check)
		[ -f "$makeParts" ] || { echo "⛔ ERROR: AgentsSessionPartsMake: no parts file at $makeParts" >&2 ; exit 1; }
		printf '%s\n' "$makeText" | cmp -s - "$makeParts" && exit 0
		echo "⛔ ERROR: AgentsSessionPartsMake: $makeParts is not what the store include gives -- run --write to regenerate it" >&2
		printf '%s\n' "$makeText" | diff -u "$makeParts" - >&2
		exit 1
	;;
	*)
		printf '%s\n' "$makeText"
	;;
esac
