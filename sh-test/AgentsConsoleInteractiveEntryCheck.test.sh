#!/usr/bin/env bash
## Behavioural check on the interactive entry of the agents console: a plain
## `bash DistroAgentsConsole.sh` with no argument, which is exactly what the editor's
## "Start Agents Console" task runs. With a harness leg (claude, copilot, scaleway) as
## the CLI service, however it was chosen, by SPAWN_CLI_SERVICE, by --cli or by the PATH
## scan, the console starts the manager screen: it runs `DistroAgentsTools.fn.sh
## --intern-manager` with no option of its own, and runs no root harness, no vendor
## binary, no claude-native and no bash console; on a pseudo-terminal the screen comes
## up and the quit key ends it; with no terminal, or where the python3 first on PATH
## cannot load curses, one error line says so, nothing else starts in its place, and the
## status is 1; a word after the flags is not handed on. The vendor binary starts only
## when the service is selected by name, claude-native / copilot-native: by --cli, or by
## the setting in a start with no terminal, which every such start of this check is (on a
## terminal a start that names no CLI is the screen: AgentsConsoleDefaultStartCheck). It
## then exports no stored key, and no screen starts. A spawn
## (--non-interactive) keeps running the harness leg. Each case has a sibling that
## differs from it in the one thing it is about. With --manager the console runs the
## same entry whatever service is configured, a vendor CLI too; with --non-interactive,
## or with a word after it, it is refused.
## The console is generated by --make-console-command into the rig's own workspace,
## then run with no MMDAPP and no MDLT_ORIGIN in the environment, so it resolves them
## from its own path and the workspace's settings as a real entry does, and reads
## SPAWN_CLI_SERVICE through the real config reader. The origin it resolves is a rig
## copy of the real tree (symlinks) whose DistroAgentsTools.fn.sh is a stub: it logs a
## call of --intern-root-harness and hands every other operation to the real one, so no
## Slack and no spawn happens; a call of --intern-manager it logs too, and then hands on,
## so the real entry of the screen is what answers. RIG_CONSOLE may name another console file to judge
## instead, for a red run. Every run goes through one `env -i` whose child refuses to
## start outside the rig tree, and a CLI named claude or copilot in its PATH is a stub
## or the run is refused: the real binary is never started.
set -u
: "${MDLT_ORIGIN:?⛔ ERROR: MDLT_ORIGIN is not set}"
rigFn="$MDLT_ORIGIN/myx/myx.distro-agents/sh-scripts/DistroAgentsTools.fn.sh"

rigRefuse(){
	echo "⛔ ERROR: $1 -- refusing to report a result" >&2 ; exit 1
}
[ -x "$rigFn" ] || rigRefuse "dispatcher not found: $rigFn"
rigTmp="$( mktemp -d -t AgentsConsoleInteractiveEntryCheck )" || exit 1
rigTmp="$( cd "$rigTmp" && pwd -P )" || exit 1
trap 'rm -rf -- "$rigTmp"' EXIT

rigPassCount=0
rigFailCount=0
rigAssert(){ ## what is asserted, got, want
	if [ "$2" = "$3" ] ; then
		printf '  PASS  %s\n' "$1" ; rigPassCount=$(( rigPassCount + 1 ))
	else
		printf '  FAIL  %s\n        got:  %s\n        want: %s\n' "$1" "$2" "$3" ; rigFailCount=$(( rigFailCount + 1 ))
	fi
}

## One console, generated once from the template by the real generator.
rigGen="$rigTmp/gen"
mkdir -p "$rigGen/ws/.local/.agents" "$rigGen/home" "$rigGen/bin"
printf 'MDLT_CONSOLE_ORIGIN=%s\n' "$MDLT_ORIGIN" > "$rigGen/ws/.local/MDLT.settings.env"
if [ -n "${RIG_CONSOLE:-}" ] ; then
	cp "$RIG_CONSOLE" "$rigGen/ws/DistroAgentsConsole.sh" || rigRefuse "could not copy the console to judge: $RIG_CONSOLE"
else
	env -i HOME="$rigGen/home" PATH="$rigGen/bin:/usr/bin:/bin" MMDAPP="$rigGen/ws" MDLT_ORIGIN="$MDLT_ORIGIN" MDLT_OPTION="--run-from-path $MDLT_ORIGIN" RIG_TMP="$rigTmp" \
		bash -c 'case "$MMDAPP" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: MMDAPP outside the rig tree" >&2 ; exit 99 ;; esac ; cd "$MMDAPP" && exec bash "$0" --make-console-command --quiet' "$rigFn" \
		> /dev/null 2> "$rigGen/make.err"
fi
[ -f "$rigGen/ws/DistroAgentsConsole.sh" ] || rigRefuse "no console was generated: $( tail -2 "$rigGen/make.err" 2>/dev/null )"

## The rig origin: every package of the real tree by symlink, and the agents package by
## symlink too except its dispatcher, which is the stub.
rigOrigin="$rigTmp/origin"
mkdir -p "$rigOrigin/myx/myx.distro-agents/sh-scripts"
for rigPkg in "$MDLT_ORIGIN"/myx/* ; do
	[ "${rigPkg##*/}" != "myx.distro-agents" ] || continue
	ln -s "$rigPkg" "$rigOrigin/myx/${rigPkg##*/}"
done
for rigPkg in "$MDLT_ORIGIN"/myx/myx.distro-agents/* ; do
	[ "${rigPkg##*/}" != "sh-scripts" ] || continue
	ln -s "$rigPkg" "$rigOrigin/myx/myx.distro-agents/${rigPkg##*/}"
done
for rigPkg in "$MDLT_ORIGIN"/myx/myx.distro-agents/sh-scripts/* ; do
	[ "${rigPkg##*/}" != "DistroAgentsTools.fn.sh" ] || continue
	ln -s "$rigPkg" "$rigOrigin/myx/myx.distro-agents/sh-scripts/${rigPkg##*/}"
done
printf '#!/bin/sh\ncase "$1" in\n\t--intern-root-harness) printf "called %%s\\n" "$*" >> "$MMDAPP/../root.log" ; printf "workspace %%s\\n" "$MMDAPP" >> "$MMDAPP/../root.log" ; exit 0 ;;\n\t--intern-manager) printf "called %%s\\n" "$*" >> "$MMDAPP/../manager.log" ;;\nesac\nexec "%s" "$@"\n' "$rigFn" \
	> "$rigOrigin/myx/myx.distro-agents/sh-scripts/DistroAgentsTools.fn.sh"
chmod +x "$rigOrigin/myx/myx.distro-agents/sh-scripts/DistroAgentsTools.fn.sh"

## A fresh workspace: the generated console, settings naming the rig origin, a configured
## service (or none) and a stored key, and a stub for each vendor CLI asked for.
rigScenario(){ ## name, SPAWN_CLI_SERVICE or empty, stored key or empty, stub names...
	rigDir="$rigTmp/$1" ; rigService="$2" ; rigKeyStored="$3" ; shift 3
	mkdir -p "$rigDir/ws/.local/.agents" "$rigDir/bin" "$rigDir/home"
	cp "$rigGen/ws/DistroAgentsConsole.sh" "$rigDir/ws/DistroAgentsConsole.sh"
	printf 'MDLT_CONSOLE_ORIGIN=%s\n' "$rigOrigin" > "$rigDir/ws/.local/MDLT.settings.env"
	: > "$rigDir/ws/.local/.agents/magic-team.agent.env"
	[ -z "$rigService" ] || printf 'SPAWN_CLI_SERVICE=%s\n' "$rigService" >> "$rigDir/ws/.local/.agents/magic-team.agent.env"
	[ -z "$rigKeyStored" ] || printf 'ANTHROPIC_API_KEY=%s\n' "$rigKeyStored" >> "$rigDir/ws/.local/.agents/magic-team.agent.env"
	: > "$rigDir/cli.log" ; : > "$rigDir/root.log" ; : > "$rigDir/manager.log"
	for rigStub in "$@" ; do
		printf '#!/bin/sh\nif [ "$1" = auth ] ; then echo "{\\"loggedIn\\":true}" ; exit 0 ; fi\nprintf "started %s key=[%%s]\\n" "${ANTHROPIC_API_KEY:-}" >> "%s/cli.log"\n' "$rigStub" "$rigDir" > "$rigDir/bin/$rigStub"
		chmod +x "$rigDir/bin/$rigStub"
	done
}
## One console run, guarded, in the entry form of the editor task: bash <console> <args...>, stdin closed.
rigEntry(){ ## console args...
	env -i HOME="$rigDir/home" PATH="$rigDir/bin:/usr/bin:/bin" RIG_TMP="$rigTmp" RIG_CONSOLE="$rigDir/ws/DistroAgentsConsole.sh" \
		bash -c '
			case "$RIG_CONSOLE" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: console outside the rig tree" >&2 ; exit 99 ;; esac
			for rigName in claude copilot ; do
				case "$( command -v "$rigName" )" in ""|"$RIG_TMP"/*) ;; *) echo "RIG-GUARD: $rigName is not a rig stub" >&2 ; exit 99 ;; esac
			done
			[ -z "${MMDAPP:-}" ] && [ -z "${MDLT_ORIGIN:-}" ] || { echo "RIG-GUARD: the entry must start with no MMDAPP and no MDLT_ORIGIN" >&2 ; exit 99 ; }
			exec bash "$RIG_CONSOLE" "$@"
		' rig "$@" < /dev/null > "$rigDir/out" 2> "$rigDir/err"
	printf '%s' "$?" > "$rigDir/rc"
}
rigStarted(){ ## name
	LC_ALL=C grep -c "^started $1 " "$rigDir/cli.log" || :
}
rigKey(){ ## name
	LC_ALL=C sed -n "s/^started $1 key=\[\(.*\)\]\$/\1/p" "$rigDir/cli.log" | head -1
}
rigHolds(){ ## file, text
	LC_ALL=C grep -q -F -- "$2" "$1" && printf yes || printf no
}
rigBashConsole(){ ## the bash console opened: its own line is on stderr
	rigHolds "$rigDir/err" 'AgentsConsole: bash console'
}
rigRootCalls(){ ## how many times the root harness was called
	LC_ALL=C grep -c '^called ' "$rigDir/root.log" || :
}
rigRootCall(){ ## the one call's arguments, exactly
	LC_ALL=C sed -n 's/^called //p' "$rigDir/root.log" | head -1
}
rigNative(){ ## how many lines of what the console printed say claude-native or copilot-native
	LC_ALL=C cat "$rigDir/out" "$rigDir/err" | LC_ALL=C grep -c -e 'claude-native' -e 'copilot-native' || :
}
rigManagerCalls(){ ## how many times the entry of the manager screen was called
	LC_ALL=C grep -c '^called ' "$rigDir/manager.log" || :
}
rigManagerCall(){ ## the one call's arguments, exactly
	LC_ALL=C sed -n 's/^called //p' "$rigDir/manager.log" | head -1
}
rigErrors(){ ## how many lines the console wrote to its error output, and how many of them hold the text
	printf '%s %s' "$( LC_ALL=C grep -c '' "$rigDir/err" || : )" "$( LC_ALL=C grep -c -F -- "$1" "$rigDir/err" || : )"
}
## The same guarded console run on a pseudo-terminal of 100 by 30, which the driver of the screen tests
## makes: once the text was drawn the keys are written. What the driver says of the run is kept in rigPty.
rigEntryPty(){ ## the text to wait for, the keys, console args...
	local ptyWait="$1" ptyKeys="$2" ; shift 2
	rigPty="$( python3 -I -B "$MDLT_ORIGIN/myx/myx.distro-agents/sh-test/check-fixtures/manager-screen.driver.py" "$MDLT_ORIGIN/myx/myx.distro-agents/sh-lib/AgentsManagerScreen.py" pty 100 30 "$ptyWait" "$ptyKeys" 90 -- \
		env -i HOME="$rigDir/home" PATH="$rigDir/bin:/usr/bin:/bin" TERM=xterm RIG_TMP="$rigTmp" RIG_CONSOLE="$rigDir/ws/DistroAgentsConsole.sh" \
		bash -c '
			case "$RIG_CONSOLE" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: console outside the rig tree" >&2 ; exit 99 ;; esac
			for rigName in claude copilot ; do
				case "$( command -v "$rigName" )" in ""|"$RIG_TMP"/*) ;; *) echo "RIG-GUARD: $rigName is not a rig stub" >&2 ; exit 99 ;; esac
			done
			[ -z "${MMDAPP:-}" ] && [ -z "${MDLT_ORIGIN:-}" ] || { echo "RIG-GUARD: the entry must start with no MMDAPP and no MDLT_ORIGIN" >&2 ; exit 99 ; }
			exec bash "$RIG_CONSOLE" "$@"
		' rig "$@" 2>&1 )"
}
rigPtyVal(){ ## name
	printf '%s\n' "$rigPty" | LC_ALL=C sed -n "s/^pty\.$1=//p" | head -1
}

echo "-- the editor task entry, claude (our harness leg) configured, the command claude in PATH, a key stored --"
rigScenario entry-claude claude rig-key-1 claude
rigEntry
rigAssert "the entry of the manager screen is called, once" "$( rigManagerCalls )" 1
rigAssert "with no option of ours"                          "$( rigManagerCall )" "--intern-manager"
rigAssert "the root harness is not called"                  "$( rigRootCalls )" 0
rigAssert "no bash console opens"                           "$( rigBashConsole )" no
rigAssert "no vendor binary is started"                     "$( rigStarted claude )" 0
rigAssert "claude-native appears nowhere in what it prints" "$( rigNative )" 0
echo "-- that run had no terminal (its output is a file): the screen says so, and nothing starts in its place --"
rigAssert "it ends with status 1"                           "$( cat "$rigDir/rc" )" 1
rigAssert "the screen says so in one line of its own, the last one written" "$( LC_ALL=C grep -c 'AgentsManagerScreen: ' "$rigDir/err" || : ) $( LC_ALL=C tail -1 "$rigDir/err" | LC_ALL=C grep -c 'ERROR: AgentsManagerScreen: the manager screen needs a terminal' || : )" "1 1"
echo "-- sibling: the same plain start on a pseudo-terminal --"
rigEntryPty "Sessions (Activity)" '\x18'
rigAssert "the screen comes up"                             "$( rigPtyVal frame )" yes
rigAssert "the quit key ends it with status 0"              "$( rigPtyVal rc )" 0
rigAssert "the terminal is left as it was"                  "$( rigPtyVal modeBack ) $( rigPtyVal errorAfterLeft )" "yes none"
rigAssert "the entry was called once more, and still no root harness and no vendor binary" "$( rigManagerCalls ) $( rigRootCalls ) $( rigStarted claude )" "2 0 0"
echo "-- sibling: the same entry, claude-native selected by name --"
rigScenario entry-native claude-native rig-key-1 claude
rigEntry
rigAssert "the vendor claude is started"                    "$( rigStarted claude )" 1
rigAssert "named claude-native, as selected"                "$( rigHolds "$rigDir/out" 'DISTRO_CONSOLE_EXEC=claude-native' )" yes
rigAssert "the root harness is not called"                  "$( rigRootCalls )" 0
rigAssert "and no manager screen: with no terminal the vendor's console stays what a plain start runs" "$( rigManagerCalls )" 0
rigAssert "and the stored key is not exported to it"        "$( rigKey claude )" ""

echo "-- the editor task entry, copilot (our harness leg) configured, the command copilot in PATH --"
rigScenario entry-copilot copilot "" copilot
rigEntry
rigAssert "the entry of the manager screen is called, once, and no root harness" "$( rigManagerCalls ) $( rigRootCalls )" "1 0"
rigAssert "no vendor binary is started"                     "$( rigStarted copilot )" 0
echo "-- sibling: copilot-native selected by name --"
rigScenario entry-copilot-native copilot-native "" copilot
rigEntry
rigAssert "the vendor copilot is started"                   "$( rigStarted copilot )" 1
rigAssert "the root harness is not called, and no manager screen" "$( rigRootCalls ) $( rigManagerCalls )" "0 0"

echo "-- the editor task entry, scaleway (a leg with no vendor binary at all) configured --"
rigScenario entry-scaleway scaleway ""
rigEntry
rigAssert "the entry of the manager screen is called, once, and no root harness" "$( rigManagerCalls ) $( rigRootCalls )" "1 0"
rigAssert "no bash console opens"                           "$( rigBashConsole )" no

echo "-- nothing configured, the command claude in PATH (the scan takes a leg): the screen starts for it too --"
rigScenario scan-claude "" "" claude
rigEntry
rigAssert "the entry of the manager screen is called, once" "$( rigManagerCalls ) $( rigManagerCall )" "1 --intern-manager"
rigAssert "no bash console opens"                           "$( rigBashConsole )" no
rigAssert "the root harness is not called"                  "$( rigRootCalls )" 0
rigAssert "no vendor binary is started"                     "$( rigStarted claude )" 0
rigAssert "it never says claude-native"                     "$( rigNative )" 0
rigAssert "with no terminal it ends with status 1, on the one line of the screen" "$( cat "$rigDir/rc" ) $( LC_ALL=C grep -c 'ERROR: AgentsManagerScreen: the manager screen needs a terminal' "$rigDir/err" || : )" "1 1"

echo "-- an explicit --cli naming the leg, the setting naming the vendor CLI: the screen starts, as for any leg --"
rigScenario explicit-leg claude-native "" claude
rigEntry --cli-auto --cli claude
rigAssert "the entry of the manager screen is called, once" "$( rigManagerCalls ) $( rigManagerCall )" "1 --intern-manager"
rigAssert "no bash console opens"                           "$( rigBashConsole )" no
rigAssert "the root harness is not called"                  "$( rigRootCalls )" 0
rigAssert "no vendor binary is started"                     "$( rigStarted claude )" 0
echo "-- a word after the flags is not handed on: the screen takes none --"
rigEntry --cli claude RIG-WORD
rigAssert "the entry is called once more, with no option and no word" "$( rigManagerCalls ) $( LC_ALL=C sed -n 's/^called //p' "$rigDir/manager.log" | LC_ALL=C tail -1 )" "2 --intern-manager"
rigAssert "and still no vendor binary and no root harness"  "$( rigStarted claude ) $( rigRootCalls )" "0 0"
echo "-- sibling: --cli names the vendor CLI --"
rigEntry --cli-auto --cli claude-native
rigAssert "the vendor claude is started"                    "$( rigStarted claude )" 1

echo "-- an explicit --cli on an interactive start is honoured over --cli-auto and the setting --"
rigScenario explicit-cli claude "" claude copilot
rigEntry --cli-auto --cli copilot-native
rigAssert "the named copilot-native is started"             "$( rigStarted copilot )" 1
rigAssert "the configured claude leg is not run"            "$( rigStarted claude )" 0
rigAssert "the root harness is not called"                  "$( rigRootCalls )" 0

echo "-- a spawn is unchanged: --non-interactive with the leg configured --"
rigScenario spawn-claude claude "" claude
rigEntry --cli-configured --non-interactive RIG-PROMPT
rigAssert "the leg is selected by name"                     "$( rigHolds "$rigDir/out" 'DISTRO_CONSOLE_EXEC=claude' )" yes
rigAssert "no vendor binary is started"                     "$( rigStarted claude )" 0
rigAssert "the root harness is not called, and no manager screen" "$( rigRootCalls ) $( rigManagerCalls )" "0 0"

echo "-- --manager on a native setup (claude-native configured, the command claude in PATH, a key stored) --"
rigScenario manager-native claude-native rig-key-1 claude
rigEntry --manager
rigAssert "the entry of the manager screen is called, once"   "$( rigManagerCalls )" 1
rigAssert "with no option of ours"                            "$( rigManagerCall )" "--intern-manager"
rigAssert "the vendor claude is not started"                  "$( rigStarted claude )" 0
rigAssert "the root harness is not called"                    "$( rigRootCalls )" 0
rigAssert "no bash console opens"                             "$( rigBashConsole )" no
rigAssert "no CLI is announced as started"                    "$( rigHolds "$rigDir/out" 'DISTRO_CONSOLE_EXEC=' )" no
echo "-- that run had no terminal (its output is a file): the screen is refused --"
rigAssert "it ends with a status that is not 0"               "$( cat "$rigDir/rc" )" 1
rigAssert "the screen says so in one line of its own, the last one written" "$( LC_ALL=C grep -c 'AgentsManagerScreen: ' "$rigDir/err" || : ) $( LC_ALL=C tail -1 "$rigDir/err" | LC_ALL=C grep -c 'ERROR: AgentsManagerScreen: the manager screen needs a terminal' || : )" "1 1"
echo "-- sibling: the same console on a pseudo-terminal --"
rigEntryPty "Sessions (Activity)" '\x18' --manager
rigAssert "the screen comes up"                               "$( rigPtyVal frame )" yes
rigAssert "the quit key ends it with status 0"                "$( rigPtyVal rc )" 0
rigAssert "the terminal is left as it was"                    "$( rigPtyVal modeBack ) $( rigPtyVal errorAfterLeft )" "yes none"
rigAssert "the entry was called once more, and still no vendor binary" "$( rigManagerCalls ) $( rigStarted claude ) $( rigRootCalls )" "2 0 0"

echo "-- --manager with a harness leg configured, as Agents --start-console gives it (--cli-auto first) --"
rigScenario manager-leg claude "" claude
rigEntry --cli-auto --manager
rigAssert "the entry of the manager screen is called, once"   "$( rigManagerCalls ) $( rigManagerCall )" "1 --intern-manager"
rigAssert "the root harness is not called"                    "$( rigRootCalls )" 0
rigAssert "no vendor binary is started"                       "$( rigStarted claude )" 0
echo "-- sibling: the same entry without --manager starts the screen as well, since its service is a leg (the first entry above) --"
rigAssert "the manager was called there too, and no root harness" "$( LC_ALL=C grep -c '^called ' "$rigTmp/entry-claude/manager.log" || : ) $( LC_ALL=C grep -c '^called ' "$rigTmp/entry-claude/root.log" || : )" "2 0"

echo "-- --manager with nothing configured and no CLI in PATH: the screen needs none --"
rigScenario manager-bare "" ""
rigEntry --manager
rigAssert "the entry of the manager screen is called"         "$( rigManagerCalls )" 1
rigAssert "no bash console opens"                             "$( rigBashConsole )" no

echo "-- refusal: --manager where the python3 first on PATH cannot load curses --"
rigScenario manager-nocurses claude-native "" claude
rigRealPython="$( command -v python3 )" || rigRefuse "no python3 on PATH to stand behind the one that cannot load curses"
printf '#!/bin/sh\nRIG_REAL_PYTHON3="%s" exec bash "%s" "$@"\n' "$rigRealPython" "$MDLT_ORIGIN/myx/myx.distro-agents/sh-test/check-fixtures/manager-screen.python3.stub.sh" > "$rigDir/bin/python3"
chmod +x "$rigDir/bin/python3"
rigEntryPty "Sessions (Activity)" '\x18' --manager
rigAssert "on a terminal too, no screen comes up"             "$( rigPtyVal frame ) $( rigPtyVal entered )" "no no"
rigAssert "it ends with a status that is not 0"               "$( rigPtyVal rc )" 1
rigAssert "one plain line says that the screen needs Python with curses" "$( rigPtyVal error | LC_ALL=C grep -c 'the manager screen needs the curses module of Python' )" 1
rigAssert "the vendor claude is not started, and no root harness" "$( rigStarted claude ) $( rigRootCalls )" "0 0"
echo "-- sibling: the same scenario with a python3 that has the module (the pseudo-terminal run above) --"
rigAssert "the screen came up there"                          "$( LC_ALL=C grep -c '^called ' "$rigTmp/manager-native/manager.log" || : )" 2

echo "-- a plain start of a leg where the python3 first on PATH cannot load curses: one line, status 1, nothing in its place --"
rigScenario leg-nocurses claude "" claude
printf '#!/bin/sh\nRIG_REAL_PYTHON3="%s" exec bash "%s" "$@"\n' "$rigRealPython" "$MDLT_ORIGIN/myx/myx.distro-agents/sh-test/check-fixtures/manager-screen.python3.stub.sh" > "$rigDir/bin/python3"
chmod +x "$rigDir/bin/python3"
rigEntryPty "Sessions (Activity)" '\x18'
rigAssert "no screen comes up"                                "$( rigPtyVal frame ) $( rigPtyVal entered )" "no no"
rigAssert "it ends with status 1, so no shell prompt was left open on the terminal" "$( rigPtyVal rc )" 1
rigAssert "one plain line says that the screen needs Python with curses" "$( rigPtyVal error | LC_ALL=C grep -c 'the manager screen needs the curses module of Python' )" 1
rigAssert "no vendor binary and no root harness start in its place" "$( rigStarted claude ) $( rigRootCalls )" "0 0"
echo "-- sibling: the same plain start with a python3 that has the module (the first entry above) --"
rigAssert "the screen came up there"                          "$( LC_ALL=C grep -c '^called ' "$rigTmp/entry-claude/manager.log" || : )" 2

echo "-- refusal: --manager with --non-interactive --"
rigScenario manager-spawn claude "" claude
rigEntry --cli-configured --manager --non-interactive RIG-PROMPT
rigAssert "it ends with a status that is not 0"               "$( cat "$rigDir/rc" )" 1
rigAssert "one error line says that they cannot be given together" "$( rigErrors '--manager starts the manager screen in a terminal, and --non-interactive starts a spawn' )" "1 1"
rigAssert "nothing is started: no screen, no leg, no vendor binary, no root harness" "$( rigManagerCalls ) $( rigHolds "$rigDir/out" 'DISTRO_CONSOLE_EXEC=' ) $( rigStarted claude ) $( rigRootCalls )" "0 no 0 0"
rigEntry --cli-configured --non-interactive --manager
rigAssert "in the other order it is refused the same way"     "$( cat "$rigDir/rc" ) $( rigErrors 'they cannot be given together' ) $( rigManagerCalls ) $( rigHolds "$rigDir/out" 'DISTRO_CONSOLE_EXEC=' )" "1 1 1 0 no"
echo "-- sibling of that refusal: the same spawn without --manager --"
rigEntry --cli-configured --non-interactive RIG-PROMPT
rigAssert "the leg is run with the prompt, as before"         "$( rigHolds "$rigDir/out" 'DISTRO_CONSOLE_EXEC=claude' ) $( rigManagerCalls )" "yes 0"

echo "-- refusal: a word after --manager --"
rigScenario manager-word claude-native "" claude
rigEntry --manager RIG-WORD
rigAssert "it is refused in one line that names the word"     "$( cat "$rigDir/rc" ) $( rigErrors '--manager takes nothing after it (got: RIG-WORD)' )" "1 1 1"
rigAssert "nothing is started"                                "$( rigManagerCalls ) $( rigStarted claude ) $( rigRootCalls )" "0 0 0"

if [ "$rigFailCount" -ne 0 ] ; then
	echo "⛔ CONSOLE INTERACTIVE ENTRY CHECK FAILED: $rigFailCount of $(( rigPassCount + rigFailCount )) assertion(s)" >&2 ; exit 1
fi
printf 'CONSOLE_INTERACTIVE_ENTRY: OK (%d assertions, offline, rig tree only)\n' "$rigPassCount"
