#!/usr/bin/env bash
## Check over the folders of sh-lib (F1.3 of the refactorings epic), read rather than run: only its rules are given,
## and its builder makes the map of each batch. sh-lib is organised in the folders board/, session/, inbox/,
## team-data/, config/, mcp/, manager/, comms/ (all outside communication: Slack, Atlassian, Google, Trello and mail), grants/,
## questions/ (the questions subsystem), harness/, member/, magic/, client/ and common/, beside the existing templates/ and help/; `intern` is not a system, so no folder is named for it. harness/
## takes every AgentsHarness* file, the universal harness and the claude files; common/ takes only the genuinely general
## ones: directory, url-post-bytes, contact, artifact. Moved to myx.distro-.local/sh-lib/, in subfolders there:
## markdown/ for the nesting engine of F2.1, output/ for formatting and template fill, registry/ for the places and
## registry primitives, dashboard/ for the panels.
## Held:
##   1. no file lies at the root of sh-lib: every one stands in a folder
##   2. every folder of sh-lib is one of the fifteen, or templates/, help/, client-hooks/ or vscode-fragments/,
##      which stay; none is named intern or op; a generated __pycache__/ is not counted
##   3. every AgentsHarness* file, AgentsUniversalHarness.sh and every AgentsClaude* file stands in harness/
##   4. every file of common/ is one of the general four, by its name
##   5. myx.distro-.local/sh-lib/ holds markdown/, output/, registry/ and dashboard/, each with a file in it
## Red before F1.3, and until its last batch: sh-lib is flat (1, 3 and 5 fail).
## Offline: it reads the packages and writes nothing.
set -u
: "${MDLT_ORIGIN:?⛔ ERROR: MDLT_ORIGIN is not set}"
rigLib="$MDLT_ORIGIN/myx/myx.distro-agents/sh-lib"
rigLocalLib="$MDLT_ORIGIN/myx/myx.distro-.local/sh-lib"
rigRefuse(){
	echo "⛔ ERROR: $1 -- refusing to report a result" >&2 ; exit 1
}
[ -d "$rigLib" ] && [ -d "$rigLocalLib" ] || rigRefuse "the sh-lib folders are not at the origin this workspace resolves: $MDLT_ORIGIN"

rigPassCount=0
rigFailCount=0
rigAssert(){ ## what is asserted, got, want
	if [ "$2" = "$3" ] ; then
		printf '  PASS  %s\n' "$1" ; rigPassCount=$(( rigPassCount + 1 ))
	else
		printf '  FAIL  %s\n        got:  %s\n        want: %s\n' "$1" "$2" "$3" ; rigFailCount=$(( rigFailCount + 1 ))
	fi
}
## The fifteen, and the folders that stay as they are: templates/, help/, client-hooks/ and vscode-fragments/. A
## __pycache__/ is generated by python, and is no folder of the package.
rigFolders="board session inbox team-data config mcp manager comms grants questions harness member magic client common templates help client-hooks vscode-fragments"
rigShort(){ ## -- the words of stdin, at most eight of them, then how many more
	LC_ALL=C awk '{ n++ ; if ( n <= 8 ) printf "%s ", $0 } END { if ( n > 8 ) printf "and %d more", n - 8 }'
}

echo "-- control: sh-lib holds files --"
rigAssert "control: sh-lib holds more than a hundred files, in it or below" "$( find "$rigLib" -type f | LC_ALL=C awk 'END { print ( NR > 100 ) ? "many" : NR }' )" many

echo "-- 1. no file lies at the root of sh-lib --"
rigAssert "the root of sh-lib holds folders only"             "[$( find "$rigLib" -mindepth 1 -maxdepth 1 -type f -exec basename {} \; | LC_ALL=C sort | rigShort )]" "[]"

echo "-- 2. every folder is one of the named ones --"
rigOdd=""
for rigFolder in $( find "$rigLib" -mindepth 1 -maxdepth 1 -type d ! -name __pycache__ -exec basename {} \; | LC_ALL=C sort ) ; do
	case " $rigFolders " in *" $rigFolder "*) ;; *) rigOdd="$rigOdd $rigFolder" ;; esac
done
rigAssert "no folder but the fifteen and the four that stay; none for intern or op" "[${rigOdd# }]" "[]"

echo "-- 3. the harness files stand in harness/ --"
rigAssert "every AgentsHarness*, AgentsUniversalHarness.sh and AgentsClaude* file is in harness/" \
	"[$( find "$rigLib" -type f \( -name 'AgentsHarness*' -o -name 'AgentsUniversalHarness.sh' -o -name 'AgentsClaude*' \) ! -path "$rigLib/harness/*" -exec basename {} \; | LC_ALL=C sort | rigShort )]" "[]"

echo "-- 4. common/ holds the general four only --"
rigAssert "every file of common/ is about a directory, url-post-bytes, a contact or an artifact" \
	"[$( find "$rigLib/common" -type f 2> /dev/null -exec basename {} \; | LC_ALL=C grep -v -i -E 'director|url-?post-?bytes|UrlPostBytes|contact|artifact' | rigShort )]" "[]"

echo "-- 5. the four folders of myx.distro-.local/sh-lib --"
rigAbsent=""
for rigFolder in markdown output registry dashboard ; do
	[ -n "$( find "$rigLocalLib/$rigFolder" -type f 2> /dev/null | head -1 )" ] || rigAbsent="$rigAbsent $rigFolder"
done
rigAssert "markdown/, output/, registry/ and dashboard/ each hold a file" "[${rigAbsent# }]" "[]"

if [ "$rigFailCount" -ne 0 ] ; then
	echo "⛔ SH-LIB FOLDERS CHECK FAILED: $rigFailCount of $(( rigPassCount + rigFailCount )) assertion(s)" >&2 ; exit 1
fi
printf 'SH_LIB_FOLDERS: OK (%d assertions, offline)\n' "$rigPassCount"
