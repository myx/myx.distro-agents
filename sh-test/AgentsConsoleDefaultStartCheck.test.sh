#!/usr/bin/env bash
## Behavioural check on THE DEFAULT OF AN INTERACTIVE START of the agents console, run rather than read. With a
## terminal on its input and on its output, a start that is no spawn (no --non-interactive) and names no CLI (no
## --cli) opens the manager screen, in every setup, one whose service is a vendor CLI too; a vendor's own console
## is started only where it is named, --cli <name>. Held form by form, each in a native setup (claude-native
## configured) and in a harness setup (the claude leg configured), with a terminal and with none: a plain start;
## --cli-auto, which is what Agents --start-console gives; Agents --start-console itself, called as a console user
## calls it, with and without --cli; --cli-configured; a word after the flags; --cli naming the vendor CLI; --cli
## naming the leg; --manager; a spawn (--non-interactive); a member's own session as the spawner starts it, which
## never shows the screen. With no terminal nothing is changed: the service that is configured is what starts, a
## leg's screen entry says in one line that it needs a terminal, and a start whose input is a terminal while its
## output is none is such a start too, by the screen's own test. The screen needs no CLI, so a setup with nothing
## configured and no CLI on PATH opens it; a vendor CLI that is named and not installed is an error, never the
## screen in its place.
## The console is generated by --make-console-command into the rig's own workspace and run with no MMDAPP and no
## MDLT_ORIGIN in the environment, as a real entry is. The origin it resolves is a rig copy of the real tree
## (symlinks) whose DistroAgentsTools.fn.sh is a stub: it logs a call of --intern-manager and ends with status 0,
## so no screen starts; with RIG_SCREEN=real it hands the call on, and the real entry of the screen answers (every
## run with no terminal, and one run on the pseudo-terminal). The terminal is a pseudo-terminal, which the driver
## of the screen's tests makes. `claude` on the rig's PATH is a stub that writes down how it was started, and the
## claude leg is pointed at a stand-in by its own lever (MDAT_CLAUDE_HARNESS): no real CLI and no harness is
## started, and every run goes through one `env -i` whose child refuses to start outside the rig tree.
## RIG_CONSOLE may name another console file to judge instead, for a red run.
set -u
: "${MDLT_ORIGIN:?⛔ ERROR: MDLT_ORIGIN is not set}"
rigFn="$MDLT_ORIGIN/myx/myx.distro-agents/sh-scripts/DistroAgentsTools.fn.sh"
rigDriver="$MDLT_ORIGIN/myx/myx.distro-agents/sh-test/check-fixtures/manager-screen.driver.py"
rigScreenFile="$MDLT_ORIGIN/myx/myx.distro-agents/sh-lib/AgentsManagerScreen.py"

rigRefuse(){
	echo "⛔ ERROR: $1 -- refusing to report a result" >&2 ; exit 1
}
[ -x "$rigFn" ] || rigRefuse "dispatcher not found: $rigFn"
[ -f "$rigDriver" ] || rigRefuse "the driver that makes the pseudo-terminal is missing from the package: $rigDriver"
rigTmp="$( mktemp -d -t AgentsConsoleDefaultStartCheck )" || exit 1
rigTmp="$( cd "$rigTmp" && pwd -P )" || exit 1
trap 'rm -rf -- "$rigTmp"' EXIT

rigPassCount=0
rigFailCount=0
rigAssert(){ ## what is asserted, got, want
	if [ "$2" = "$3" ] ; then
		printf '  PASS  %s\n' "$1" ; rigPassCount=$(( rigPassCount + 1 ))
	else
		printf '  FAIL  %s\n        got:  %s\n        want: %s\n' "$1" "$2" "$3" ; rigFailCount=$(( rigFailCount + 1 ))
	fi
}

## One console, generated once from the template by the real generator.
rigGen="$rigTmp/gen"
mkdir -p "$rigGen/ws/.local/.agents" "$rigGen/home" "$rigGen/bin"
printf 'MDLT_CONSOLE_ORIGIN=%s\n' "$MDLT_ORIGIN" > "$rigGen/ws/.local/MDLT.settings.env"
if [ -n "${RIG_CONSOLE:-}" ] ; then
	cp "$RIG_CONSOLE" "$rigGen/ws/DistroAgentsConsole.sh" || rigRefuse "could not copy the console to judge: $RIG_CONSOLE"
else
	env -i HOME="$rigGen/home" PATH="$rigGen/bin:/usr/bin:/bin" MMDAPP="$rigGen/ws" MDLT_ORIGIN="$MDLT_ORIGIN" MDLT_OPTION="--run-from-path $MDLT_ORIGIN" RIG_TMP="$rigTmp" \
		bash -c 'case "$MMDAPP" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: MMDAPP outside the rig tree" >&2 ; exit 99 ;; esac ; cd "$MMDAPP" && exec bash "$0" --make-console-command --quiet' "$rigFn" \
		> /dev/null 2> "$rigGen/make.err"
fi
[ -f "$rigGen/ws/DistroAgentsConsole.sh" ] || rigRefuse "no console was generated: $( tail -2 "$rigGen/make.err" 2>/dev/null )"

## The rig origin: every package of the real tree by symlink, and the agents package by symlink too except its
## dispatcher, which is the stub.
rigOrigin="$rigTmp/origin"
mkdir -p "$rigOrigin/myx/myx.distro-agents/sh-scripts"
for rigPkg in "$MDLT_ORIGIN"/myx/* ; do
	[ "${rigPkg##*/}" != "myx.distro-agents" ] || continue
	ln -s "$rigPkg" "$rigOrigin/myx/${rigPkg##*/}"
done
for rigPkg in "$MDLT_ORIGIN"/myx/myx.distro-agents/* ; do
	[ "${rigPkg##*/}" != "sh-scripts" ] || continue
	ln -s "$rigPkg" "$rigOrigin/myx/myx.distro-agents/${rigPkg##*/}"
done
for rigPkg in "$MDLT_ORIGIN"/myx/myx.distro-agents/sh-scripts/* ; do
	[ "${rigPkg##*/}" != "DistroAgentsTools.fn.sh" ] || continue
	ln -s "$rigPkg" "$rigOrigin/myx/myx.distro-agents/sh-scripts/${rigPkg##*/}"
done
printf '#!/bin/sh\ncase "$1" in\n\t--intern-manager)\n\t\tprintf "called %%s\\n" "$*" >> "$MMDAPP/../manager.log"\n\t\t[ "${RIG_SCREEN:-}" = real ] || exit 0\n\t;;\nesac\nexec "%s" "$@"\n' "$rigFn" \
	> "$rigOrigin/myx/myx.distro-agents/sh-scripts/DistroAgentsTools.fn.sh"
chmod +x "$rigOrigin/myx/myx.distro-agents/sh-scripts/DistroAgentsTools.fn.sh"

## A fresh workspace: the generated console, settings naming the rig origin, a configured service (or none), a
## stub for each vendor CLI asked for, and the stand-in the claude leg is pointed at.
rigScenario(){ ## name, SPAWN_CLI_SERVICE or empty, stub names...
	rigDir="$rigTmp/$1" ; rigService="$2" ; shift 2
	mkdir -p "$rigDir/ws/.local/.agents" "$rigDir/bin" "$rigDir/home"
	cp "$rigGen/ws/DistroAgentsConsole.sh" "$rigDir/ws/DistroAgentsConsole.sh"
	printf 'MDLT_CONSOLE_ORIGIN=%s\n' "$rigOrigin" > "$rigDir/ws/.local/MDLT.settings.env"
	: > "$rigDir/ws/.local/.agents/magic-team.agent.env"
	[ -z "$rigService" ] || printf 'SPAWN_CLI_SERVICE=%s\n' "$rigService" >> "$rigDir/ws/.local/.agents/magic-team.agent.env"
	for rigStub in "$@" ; do
		printf '#!/bin/sh\nif [ "$1" = auth ] ; then echo "{\\"loggedIn\\":true}" ; exit 0 ; fi\nrigTty=no ; [ -t 0 ] && [ -t 1 ] && rigTty=yes\n{ printf "started %s tty=%%s args=" "$rigTty" ; for rigArg in "$@" ; do printf "[%%s]" "$rigArg" ; done ; printf "\\n" ; } >> "%s/cli.log"\n' "$rigStub" "$rigDir" > "$rigDir/bin/$rigStub"
		chmod +x "$rigDir/bin/$rigStub"
	done
	printf '#!/bin/sh\nHARNESS_CREDENTIAL_NAMES="RIG_NO_SUCH_CREDENTIAL"\n{ printf "leg args=" ; for rigArg in "$@" ; do printf "[%%s]" "$rigArg" ; done ; printf "\\n" ; } >> "%s/leg.log"\n' "$rigDir" > "$rigDir/bin/leg-stand-in"
	chmod +x "$rigDir/bin/leg-stand-in"
	rigPre=()
	rigScreen=""
	rigReset
}
rigReset(){ ## the logs of the next run are its own
	: > "$rigDir/cli.log" ; : > "$rigDir/manager.log" ; : > "$rigDir/leg.log" ; : > "$rigDir/out" ; : > "$rigDir/err"
}
## What every run is started through: refused outside the rig tree, with a CLI that is no rig stub, or with the
## workspace or the origin already named.
rigGuard='
	case "$RIG_CONSOLE" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: console outside the rig tree" >&2 ; exit 99 ;; esac
	for rigName in claude copilot grok ; do
		case "$( command -v "$rigName" )" in ""|"$RIG_TMP"/*) ;; *) echo "RIG-GUARD: $rigName is not a rig stub" >&2 ; exit 99 ;; esac
	done
	[ -z "${MMDAPP:-}" ] && [ -z "${MDLT_ORIGIN:-}" ] || { echo "RIG-GUARD: the entry must start with no MMDAPP and no MDLT_ORIGIN" >&2 ; exit 99 ; }
'
## One console run with NO TERMINAL, in the entry form of the editor task: bash <console> <args...>, its input
## closed and its output a file. The screen entry is the real one, so what it says is what a user reads.
rigEntry(){ ## console args...
	rigReset
	env -i HOME="$rigDir/home" PATH="$rigDir/bin:/usr/bin:/bin" RIG_TMP="$rigTmp" RIG_CONSOLE="$rigDir/ws/DistroAgentsConsole.sh" RIG_SCREEN=real MDAT_CLAUDE_HARNESS="$rigDir/bin/leg-stand-in" ${rigPre[@]+"${rigPre[@]}"} \
		bash -c "$rigGuard"' exec bash "$RIG_CONSOLE" "$@"' rig "$@" < /dev/null > "$rigDir/out" 2> "$rigDir/err"
	rigRc=$?
}
## The same run WITH A TERMINAL: a pseudo-terminal of 100 by 30. What the driver says of the run is kept in rigPty.
rigEntryPty(){ ## the text to wait for, the keys, console args...
	local ptyWait="$1" ptyKeys="$2" ; shift 2
	rigReset
	rigPty="$( python3 -I -B "$rigDriver" "$rigScreenFile" pty 100 30 "$ptyWait" "$ptyKeys" 90 -- \
		env -i HOME="$rigDir/home" PATH="$rigDir/bin:/usr/bin:/bin" TERM=xterm RIG_TMP="$rigTmp" RIG_CONSOLE="$rigDir/ws/DistroAgentsConsole.sh" RIG_SCREEN="$rigScreen" RIG_OUT="$rigDir/out" MDAT_CLAUDE_HARNESS="$rigDir/bin/leg-stand-in" ${rigPre[@]+"${rigPre[@]}"} \
		bash -c "$rigGuard"' if [ "$1" = RIG-OUTPUT-TO-FILE ] ; then shift ; exec bash "$RIG_CONSOLE" "$@" > "$RIG_OUT" ; fi ; exec bash "$RIG_CONSOLE" "$@"' rig "$@" 2>&1 )"
	rigRc="$( rigPtyVal rc )"
}
## Agents --start-console on that pseudo-terminal, as a console user calls it: the workspace and the origin are
## named, the context is sourced, and the function is called with the words given.
rigAgentsPty(){ ## Agents arguments...
	rigReset
	rigPty="$( python3 -I -B "$rigDriver" "$rigScreenFile" pty 100 30 - - 90 -- \
		env -i HOME="$rigDir/home" PATH="$rigDir/bin:/usr/bin:/bin" TERM=xterm RIG_TMP="$rigTmp" MMDAPP="$rigDir/ws" MDLT_ORIGIN="$rigOrigin" RIG_SCREEN="$rigScreen" MDAT_CLAUDE_HARNESS="$rigDir/bin/leg-stand-in" \
		bash -c '
			case "$MMDAPP" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: workspace outside the rig tree" >&2 ; exit 99 ;; esac
			case "$MDLT_ORIGIN" in "$RIG_TMP"/*) ;; *) echo "RIG-GUARD: origin outside the rig tree" >&2 ; exit 99 ;; esac
			for rigName in claude copilot grok ; do
				case "$( command -v "$rigName" )" in ""|"$RIG_TMP"/*) ;; *) echo "RIG-GUARD: $rigName is not a rig stub" >&2 ; exit 99 ;; esac
			done
			cd "$MMDAPP" || exit 99
			rigWords=( "$@" ) ; set --
			. "$MDLT_ORIGIN/myx/myx.distro-agents/sh-lib/AgentsContext.include" || exit 98
			Agents "${rigWords[@]}"
		' rig "$@" 2>&1 )"
	rigRc="$( rigPtyVal rc )"
}
rigPtyVal(){ ## name
	printf '%s\n' "$rigPty" | LC_ALL=C sed -n "s/^pty\.$1=//p" | head -1
}
rigManager(){ ## how many times the entry of the manager screen was called, and with what the first time
	printf '%s [%s]' "$( LC_ALL=C grep -c '^called ' "$rigDir/manager.log" || : )" "$( LC_ALL=C sed -n 's/^called //p' "$rigDir/manager.log" | head -1 )"
}
rigVendor(){ ## how many times the vendor claude was started
	LC_ALL=C grep -c '^started claude ' "$rigDir/cli.log" || :
}
rigVendorTty(){ ## whether it had a terminal on its input and its output, the one time it was started
	LC_ALL=C sed -n 's/^started claude tty=\([a-z]*\) .*$/\1/p' "$rigDir/cli.log" | head -1
}
rigVendorHas(){ ## fixed text -- whether the words it was started with hold it
	LC_ALL=C grep '^started claude ' "$rigDir/cli.log" | LC_ALL=C grep -q -F -- "$1" && printf yes || printf no
}
rigLeg(){ ## how many times the stand-in of the claude leg was started
	LC_ALL=C grep -c '^leg ' "$rigDir/leg.log" || :
}
rigLegHas(){ ## fixed text -- whether the words it was started with hold it
	LC_ALL=C grep -q -F -- "$1" "$rigDir/leg.log" && printf yes || printf no
}
rigNeedsTerminal(){ ## how many lines of the last error output are the screen's own line that it needs a terminal
	LC_ALL=C grep -c 'ERROR: AgentsManagerScreen: the manager screen needs a terminal' "$rigDir/err" || :
}
rigScreenOnly="1 [--intern-manager]"

echo "-- 1. WITH A TERMINAL, a native setup (claude-native configured, the command claude on PATH) --"
rigScenario native-pty claude-native claude
rigEntryPty - -
rigAssert "a plain start opens the manager screen: its entry is called once, with no option, and ends as it ends" "$( rigManager ) $rigRc" "$rigScreenOnly 0"
rigAssert "and the vendor's console is not started"                    "$( rigVendor )" 0
rigEntryPty - - --cli-auto
rigAssert "--cli-auto, which is what Agents --start-console gives, opens the screen too, and no vendor console" "$( rigManager ) $( rigVendor )" "$rigScreenOnly 0"
rigAgentsPty --start-console
rigAssert "Agents --start-console itself opens the screen, and no vendor console" "$( rigManager ) $( rigVendor )" "$rigScreenOnly 0"
rigEntryPty - - --cli-configured
rigAssert "--cli-configured names no CLI either: the screen, and no vendor console" "$( rigManager ) $( rigVendor )" "$rigScreenOnly 0"
rigEntryPty - - --cli-auto RIG-WORD
rigAssert "a word after the flags is not handed on, and names no CLI: the screen, with no option and no word" "$( rigManager ) $( rigVendor )" "$rigScreenOnly 0"
echo "-- sibling: the same starts with the vendor CLI named --"
rigEntryPty - - --cli claude-native
rigAssert "--cli claude-native starts the vendor's console, once, on the terminal" "$( rigVendor ) $( rigVendorTty ) $rigRc" "1 yes 0"
rigAssert "and no manager screen, and it is no spawn: no prompt option"  "$( rigManager ) $( rigVendorHas '[-p]' )" "0 [] no"
rigEntryPty - - --cli-auto --cli claude-native
rigAssert "--cli-auto --cli claude-native, which is what Agents --start-console --cli claude-native gives, starts it too" "$( rigVendor ) $( rigVendorTty ) $( rigManager )" "1 yes 0 []"
rigAgentsPty --start-console --cli claude-native
rigAssert "Agents --start-console --cli claude-native itself starts the vendor's console on the terminal, and no screen" "$( rigVendor ) $( rigVendorTty ) $( rigManager )" "1 yes 0 []"
echo "-- the forms that say what they start are as they were --"
rigEntryPty - - --cli claude
rigAssert "--cli naming the leg: the screen, and no vendor console"     "$( rigManager ) $( rigVendor ) $( rigLeg )" "$rigScreenOnly 0 0"
rigEntryPty - - --manager
rigAssert "--manager: the screen, and no vendor console"                "$( rigManager ) $( rigVendor )" "$rigScreenOnly 0"
rigEntryPty - - --cli-configured --non-interactive RIG-PROMPT
rigAssert "a spawn on a terminal is a spawn: the vendor CLI with the prompt, and no screen" "$( rigVendor ) $( rigVendorHas '[-p][--][RIG-PROMPT]' ) $( rigManager )" "1 yes 0 []"
rigPre=( "MDAT_SPAWN_AGENT=keeper-rig" "MDAT_SPAWN_SESSION_ID=00000000-0000-4000-8000-00000000d1a6" )
rigEntryPty - - --cli-configured --non-interactive RIG-PROMPT
rigPre=()
rigAssert "a member's own session, as the spawner starts it, never shows the screen: the vendor CLI as that member, with the prompt" \
	"$( rigVendor ) $( rigVendorHas '[--agent][keeper-rig]' ) $( rigVendorHas '[--session-id][00000000-0000-4000-8000-00000000d1a6]' ) $( rigVendorHas '[-p][--][RIG-PROMPT]' ) $( rigManager )" "1 yes yes yes 0 []"
echo "-- the plain start once more, with the real entry of the screen behind it --"
## The keys that end the screen are the screen's own matter, and none of this check: `q`, which ended it once,
## and then Ctrl-x, which ends it now, so the start is judged here whichever of them the screen has.
rigScreen=real
rigEntryPty "Sessions (Activity)" 'q\p\x18'
rigScreen=""
rigAssert "the screen comes up on the terminal, and its exit key ends it with status 0" "$( rigPtyVal frame ) $rigRc" "yes 0"
rigAssert "the terminal is left as it was, and no vendor console was started" "$( rigPtyVal modeBack ) $( rigPtyVal errorAfterLeft ) $( rigVendor )" "yes none 0"

echo "-- 2. WITH A TERMINAL, a harness setup (the claude leg configured, the command claude on PATH) --"
rigScenario harness-pty claude claude
rigEntryPty - -
rigAssert "a plain start opens the manager screen, as it did"           "$( rigManager ) $( rigVendor ) $( rigLeg ) $rigRc" "$rigScreenOnly 0 0 0"
rigEntryPty - - --cli-auto
rigAssert "--cli-auto opens it too"                                     "$( rigManager ) $( rigVendor ) $( rigLeg )" "$rigScreenOnly 0 0"
rigAgentsPty --start-console
rigAssert "and Agents --start-console"                                  "$( rigManager ) $( rigVendor ) $( rigLeg )" "$rigScreenOnly 0 0"
rigEntryPty - - --cli claude-native
rigAssert "--cli claude-native starts the vendor's console here as well, on the terminal, and no screen" "$( rigVendor ) $( rigVendorTty ) $( rigManager ) $( rigLeg )" "1 yes 0 [] 0"
rigAgentsPty --start-console --cli claude-native
rigAssert "and so does Agents --start-console --cli claude-native"      "$( rigVendor ) $( rigVendorTty ) $( rigManager )" "1 yes 0 []"
rigEntryPty - - --manager
rigAssert "--manager: the screen"                                       "$( rigManager ) $( rigVendor ) $( rigLeg )" "$rigScreenOnly 0 0"
rigEntryPty - - --cli-configured --non-interactive RIG-PROMPT
rigAssert "a spawn on a terminal is a spawn: the leg with the prompt, no screen and no vendor CLI" "$( rigLeg ) $( rigLegHas '[RIG-PROMPT]' ) $( rigManager ) $( rigVendor )" "1 yes 0 [] 0"
rigPre=( "MDAT_SPAWN_AGENT=keeper-rig" "MDAT_SPAWN_SESSION_ID=00000000-0000-4000-8000-00000000d1a6" )
rigEntryPty - - --cli-configured --non-interactive RIG-PROMPT
rigPre=()
rigAssert "a member's own session never shows the screen: the leg as that member, with the prompt" \
	"$( rigLeg ) $( rigLegHas '[--agent][keeper-rig]' ) $( rigLegHas '[RIG-PROMPT]' ) $( rigManager ) $( rigVendor )" "1 yes yes 0 [] 0"

echo "-- 3. WITH NO TERMINAL, the native setup: nothing is changed --"
rigScenario native-none claude-native claude
rigEntry
rigAssert "a plain start starts the vendor's console, as it did, and no screen" "$( rigVendor ) $( rigVendorTty ) $( rigManager ) $rigRc" "1 no 0 [] 0"
rigAssert "named claude-native, as configured"                          "$( LC_ALL=C grep -c -x 'DISTRO_CONSOLE_EXEC=claude-native' "$rigDir/out" || : )" 1
rigEntry --cli-auto
rigAssert "--cli-auto starts it too"                                    "$( rigVendor ) $( rigManager )" "1 0 []"
rigEntry --cli claude-native
rigAssert "and --cli claude-native"                                     "$( rigVendor ) $( rigManager )" "1 0 []"
rigEntry --manager
rigAssert "--manager calls the entry of the screen, which says in one line that it needs a terminal: status 1, no vendor console" "$( rigManager ) $( rigNeedsTerminal ) $rigRc $( rigVendor )" "$rigScreenOnly 1 1 0"
rigEntry --cli-configured --non-interactive RIG-PROMPT
rigAssert "a spawn: the vendor CLI with the prompt, and no screen"      "$( rigVendor ) $( rigVendorHas '[-p][--][RIG-PROMPT]' ) $( rigManager )" "1 yes 0 []"
echo "-- sibling: its input is a terminal and its output is a file, which is no terminal by the screen's own test --"
rigEntryPty - - RIG-OUTPUT-TO-FILE
rigAssert "the vendor's console is started, as with no terminal, and no screen" "$( rigVendor ) $( rigVendorTty ) $( rigManager )" "1 no 0 []"

echo "-- 4. WITH NO TERMINAL, the harness setup: nothing is changed --"
rigScenario harness-none claude claude
rigEntry
rigAssert "a plain start calls the entry of the screen, which says in one line that it needs a terminal: status 1" "$( rigManager ) $( rigNeedsTerminal ) $rigRc" "$rigScreenOnly 1 1"
rigAssert "and nothing starts in its place"                             "$( rigVendor ) $( rigLeg )" "0 0"
rigEntry --cli-auto
rigAssert "--cli-auto does the same"                                    "$( rigManager ) $( rigNeedsTerminal ) $rigRc $( rigVendor )" "$rigScreenOnly 1 1 0"
rigEntry --cli claude-native
rigAssert "--cli claude-native starts the vendor's console, and no screen" "$( rigVendor ) $( rigManager )" "1 0 []"
rigEntry --cli-configured --non-interactive RIG-PROMPT
rigAssert "a spawn: the leg with the prompt, and no screen"             "$( rigLeg ) $( rigLegHas '[RIG-PROMPT]' ) $( rigManager ) $( rigVendor )" "1 yes 0 [] 0"

echo "-- 5. WITH A TERMINAL, nothing configured and no CLI on PATH: the screen needs none --"
rigScenario bare-pty ""
rigEntryPty - -
rigAssert "a plain start opens the manager screen"                      "$( rigManager ) $rigRc" "$rigScreenOnly 0"
rigEntryPty - - --cli claude-native
rigAssert "a vendor CLI that is named and not installed is an error, status 1, and the screen does not start in its place" "$rigRc $( rigManager ) $( rigPtyVal error | LC_ALL=C grep -c -F -- "'claude-native' CLI not found in PATH" || : )" "1 0 [] 1"

if [ "$rigFailCount" -ne 0 ] ; then
	echo "⛔ CONSOLE DEFAULT START CHECK FAILED: $rigFailCount of $(( rigPassCount + rigFailCount )) assertion(s)" >&2 ; exit 1
fi
printf 'CONSOLE_DEFAULT_START: OK (%d assertions, offline, rig tree only)\n' "$rigPassCount"
